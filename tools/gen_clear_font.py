"""Regenerate the glyph table of crates/client/src/clearfont/glyphs.rs from Pixel Operator Bold.

    uv run --with pillow python tools/gen_clear_font.py PATH/TO/PixelOperator-Bold.ttf

Pixel Operator by Jayvee Enaguas is under CC0 1.0 (public domain); see THIRD_PARTY_NOTICES.md. The font is drawn on a
16-pixel grid, so rendering it at 16 pixels without smoothing gives its pixels exactly. (Other sizes lose pixels: at
20 the thin diagonals of M, N, W, K and others vanish.) For each printable ASCII character from '!' to '~' this writes
the inked columns' width, the top row of the ink relative to the baseline, and one bit mask per row (bit 0 the
leftmost pixel).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "client", "src", "clearfont", "glyphs.rs")


def table(size):
    font = ImageFont.truetype(sys.argv[1], size)
    ascent, descent = font.getmetrics()
    # The baseline row: the bottom of 'H' (no descender).
    probe = Image.new("1", (size * 2, ascent + descent + 4), 0)
    ImageDraw.Draw(probe).text((2, 0), "H", font=font, fill=1)
    baseline = probe.getbbox()[3] - 1
    rows_out = []
    for code in range(0x21, 0x7F):
        im = Image.new("1", (size * 2, ascent + descent + 4), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((2, 0), chr(code), font=font, fill=1)
        box = im.getbbox()
        if box is None:
            raise SystemExit(f"no ink for {code:#x}")
        left, top, right, bottom = box
        masks = []
        for y in range(top, bottom):
            m = 0
            for x in range(left, right):
                if im.getpixel((x, y)):
                    m |= 1 << (x - left)
            masks.append(m)
        width = right - left
        if width > 16:
            raise SystemExit(f"{chr(code)!r} is {width} wide")
        rows = ", ".join(f"0x{m:04x}" for m in masks)
        char = {"'": "\\'", "\\": "\\\\"}.get(chr(code), chr(code))
        rows_out.append(f"    ('{char}', {width}, {top - baseline}, &[{rows}]),")
    return "\n".join(rows_out)


open(OUT, "w", encoding="utf-8").write(
    "//! Generated by `tools/gen_clear_font.py` from Pixel Operator Bold (CC0 1.0, see `THIRD_PARTY_NOTICES.md`). Do not\n"
    "//! edit by hand.\n"
    "\n"
    "/// Each printable ASCII character from '!' to '~': the inked width, the ink's top row relative to the baseline\n"
    "/// (negative is above it), and one bit mask per row, bit 0 the leftmost pixel. 9-pixel capitals, 2-pixel strokes.\n"
    "#[rustfmt::skip]\n"
    "pub(super) const GLYPHS: [(char, u8, i8, &[u16]); 94] = [\n"
    f"{table(16)}\n"
    "];\n"
)
print(f"wrote {OUT}")
